class _StreamlitUploadAdapter:
    """Shim so a Streamlit UploadedFile can be passed to IngestionService.ingest_upload(),
    which only ever touches `.filename` and `.file.read(n)` -- it doesn't require an
    actual fastapi.UploadFile instance, just those two attributes."""

