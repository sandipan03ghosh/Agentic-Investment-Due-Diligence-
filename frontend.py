def safe_slug(title: str) -> str:
    s = title.strip().lower()
    s = re.sub(r"[^a-z0-9 _-]+", "", s)
    s = re.sub(r"\s+", "_", s).strip("_")
    return s or "blog"


def bundle_zip(md_text: str, md_filename: str, images_dir: Path) -> bytes:
    buf = BytesIO()
    with zipfile.ZipFile(buf, "w", compression=zipfile.ZIP_DEFLATED) as z:
        z.writestr(md_filename, md_text.encode("utf-8"))

        if images_dir.exists() and images_dir.is_dir():
            for p in images_dir.rglob("*"):
                if p.is_file():
                    z.write(p, arcname=str(p))
    return buf.getvalue()


def images_zip(images_dir: Path) -> Optional[bytes]:
    if not images_dir.exists() or not images_dir.is_dir():
        return None
    buf = BytesIO()
    with zipfile.ZipFile(buf, "w", compression=zipfile.ZIP_DEFLATED) as z:
        for p in images_dir.rglob("*"):
            if p.is_file():
                z.write(p, arcname=str(p))
    return buf.getvalue()


# -----------------------------
# Markdown renderer that supports local images
# -----------------------------
_MD_IMG_RE = re.compile(r"!\[(?P<alt>[^\]]*)\]\((?P<src>[^)]+)\)")
_CAPTION_LINE_RE = re.compile(r"^\*(?P<cap>.+)\*$")


_ALLOWED_IMAGE_EXTENSIONS = {".png", ".jpg", ".jpeg", ".gif", ".webp", ".svg"}

# Same "images" directory convention already used by generate_and_place_images() in
# backend.py and by images_zip()/bundle_zip() below -- not a new location.
_IMAGES_DIR = Path("images")


def _resolve_image_path(src: str) -> Optional[Path]:
    """Resolve a markdown image reference to a local file, strictly confined to the
    images/ directory this app already writes generated images into -- the existing
    trusted directory, not a new one.

    Returns None for anything that would escape it (absolute paths, ../ traversal,
    or a symlink inside images/ whose real target resolves outside it) so the
    caller can skip the reference gracefully instead of ever opening/displaying it.
    """
    src = src.strip()
    if not src:
        return None

    candidate = Path(src)
    # Fast-path rejection for obviously absolute input. This is a cheap pre-check,
    # NOT the security boundary -- pathlib's is_absolute() has platform quirks
    # (e.g. "/etc/passwd" is not considered absolute on Windows), so it must never
    # be relied on alone; the relative_to() check below is authoritative regardless.
    if candidate.is_absolute():
        return None

    if candidate.suffix.lower() not in _ALLOWED_IMAGE_EXTENSIONS:
        return None

    # Markdown generated by backend.py already writes refs as "images/<filename>".
    # Drop a leading "images" component if present so both that form and a bare
    # "<filename>" resolve the same way, always anchored under base_dir below --
    # never onto the process's current working directory.
    parts = candidate.parts
    if parts and parts[0].lower() == _IMAGES_DIR.name.lower():
        candidate = Path(*parts[1:]) if len(parts) > 1 else Path()

    # Resolved fresh on every call (not cached) so the containment check always
    # reflects the current filesystem state.
    base_dir = _IMAGES_DIR.resolve()
    try:
        resolved = (base_dir / candidate).resolve()
    except (OSError, RuntimeError):
        return None

    # The real containment check: resolve() follows symlinks and normalizes ".."
    # segments, so `resolved` is the actual real path the OS would open. relative_to()
    # raises ValueError if that real path is not base_dir itself or a descendant of
    # it -- an ancestry check on the resolved path, not a string-prefix comparison.
    try:
        resolved.relative_to(base_dir)
    except ValueError:
        return None

    return resolved


def render_markdown_with_local_images(md: str):
    matches = list(_MD_IMG_RE.finditer(md))
    if not matches:
        st.markdown(md, unsafe_allow_html=False)
        return

    parts: List[Tuple[str, str]] = []
    last = 0
    for m in matches:
        before = md[last : m.start()]
        if before:
            parts.append(("md", before))

        alt = (m.group("alt") or "").strip()
        src = (m.group("src") or "").strip()
        parts.append(("img", f"{alt}|||{src}"))
        last = m.end()

    tail = md[last:]
    if tail:
        parts.append(("md", tail))

    i = 0
    while i < len(parts):
        kind, payload = parts[i]

        if kind == "md":
            st.markdown(payload, unsafe_allow_html=False)
            i += 1
            continue

        alt, src = payload.split("|||", 1)

        caption = None
        if i + 1 < len(parts) and parts[i + 1][0] == "md":
            nxt = parts[i + 1][1].lstrip()
            if nxt.strip():
                first_line = nxt.splitlines()[0].strip()
                mcap = _CAPTION_LINE_RE.match(first_line)
                if mcap:
                    caption = mcap.group("cap").strip()
                    rest = "\n".join(nxt.splitlines()[1:])
                    parts[i + 1] = ("md", rest)

        if src.startswith("http://") or src.startswith("https://"):
            st.image(src, caption=caption or (alt or None), use_container_width=True)
        else:
            img_path = _resolve_image_path(src)
            if img_path is not None and img_path.exists():
                st.image(str(img_path), caption=caption or (alt or None), use_container_width=True)
            else:
                st.warning(f"Image not found: `{src}` (looked for `{img_path}`)")

        i += 1


