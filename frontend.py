def _require_app_access() -> None:
    """Password gate for the whole app (report generation + KB upload + past-report
    browsing) -- runs first, before any other content, and st.stop()s the script if
    not authenticated. This is the fix for the trust-boundary gap noted earlier: the
    KB-upload button calls the ingestion service in-process, bypassing the ingestion
    API's own INGESTION_API_KEY check entirely, so without this gate anyone who can
    load this page could ingest documents. A no-op (APP_ACCESS_KEY unset) only for
    local/dev use -- the visible warning below makes that state impossible to miss
    rather than silently open, mirroring the same pattern used for INGESTION_API_KEY
    in ingestion/api.py."""
    if not settings.APP_ACCESS_KEY:
        st.warning(
            "APP_ACCESS_KEY is not set — this app is running with no access gate. "
            "Set it before exposing this app beyond your own machine.",
            icon="⚠️",
        )
        return

    if st.session_state.get("app_authenticated"):
        return

    st.title("🔒 Access Required")
    entered = st.text_input("Access key", type="password", key="app_access_key_input")
    if st.button("Unlock"):
        if hmac.compare_digest(entered, settings.APP_ACCESS_KEY):
            st.session_state["app_authenticated"] = True
            st.rerun()
        else:
            st.error("Incorrect access key.")
    st.stop()


